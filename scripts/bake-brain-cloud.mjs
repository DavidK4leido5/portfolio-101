/**
 * Bake anatomical brain OBJ → surface point cloud + lobe hotspots.
 * Source: sage repo brain.obj (CC BY 4.0, FrankJohansson / Sketchfab)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OBJ = join(ROOT, 'scripts', 'brain.obj')
const OUT = join(ROOT, 'src', 'data', 'brainCloud.ts')
const TARGET = 24000
const SCALE = 6.8 // baked mesh extent; CLUSTER_SCALE in shared.ts adds display size

const text = readFileSync(OBJ, 'utf8')
const verts = []
const faces = []

for (const line of text.split('\n')) {
  if (line.startsWith('v ')) {
    const [, x, y, z] = line.split(/\s+/)
    verts.push([+x, +y, +z])
  } else if (line.startsWith('f ')) {
    const idx = line.trim().split(/\s+/).slice(1).map((p) => +p.split('/')[0] - 1)
    if (idx.length >= 3) faces.push(idx)
  }
}

function triArea(a, b, c) {
  const ab = [b[0] - a[0], b[1] - a[1], b[2] - a[2]]
  const ac = [c[0] - a[0], c[1] - a[1], c[2] - a[2]]
  const cx = ab[1] * ac[2] - ab[2] * ac[1]
  const cy = ab[2] * ac[0] - ab[0] * ac[2]
  const cz = ab[0] * ac[1] - ab[1] * ac[0]
  return 0.5 * Math.hypot(cx, cy, cz)
}

function sampleTri(a, b, c) {
  let u = Math.random(), v = Math.random()
  if (u + v > 1) { u = 1 - u; v = 1 - v }
  const w = 1 - u - v
  return [a[0] * u + b[0] * v + c[0] * w, a[1] * u + b[1] * v + c[1] * w, a[2] * u + b[2] * v + c[2] * w]
}

// Area-weighted surface sampling
const tris = []
let totalArea = 0
for (const f of faces) {
  const a = verts[f[0]], b = verts[f[1]], c = verts[f[2]]
  const area = triArea(a, b, c)
  if (area > 0) { tris.push({ a, b, c, area }); totalArea += area }
}

const raw = []
for (let i = 0; i < TARGET; i++) {
  let r = Math.random() * totalArea
  for (const t of tris) {
    r -= t.area
    if (r <= 0) { raw.push(sampleTri(t.a, t.b, t.c)); break }
  }
}

// Center + scale + orient (mesh Y-up; flip Z so face points +Z)
let cx = 0, cy = 0, cz = 0
for (const p of raw) { cx += p[0]; cy += p[1]; cz += p[2] }
cx /= raw.length; cy /= raw.length; cz /= raw.length

const norm = raw.map(([x, y, z]) => [x - cx, y - cy, z - cz])
let maxExt = 0
for (const p of norm) maxExt = Math.max(maxExt, ...p.map(Math.abs))

const s = SCALE / (maxExt * 2)
const surface = norm.map(([x, y, z]) => [x * s, y * s, -z * s])

function regionCentroid(filter) {
  const pts = surface.filter(filter)
  if (!pts.length) return [0, 0, 0]
  let x = 0, y = 0, z = 0
  for (const p of pts) { x += p[0]; y += p[1]; z += p[2] }
  return [x / pts.length, y / pts.length, z / pts.length]
}

const hotspots = {
  projects: regionCentroid((p) => p[0] > 1.3 && p[1] > 0.65 && p[2] > 1.15),
  experience: regionCentroid((p) => p[0] < -1.45 && p[1] > 1.5 && Math.abs(p[2]) < 1.15),
  skills: regionCentroid((p) => p[0] > 1.55 && p[1] > -0.25 && p[1] < 0.95 && p[2] > 0.25),
  about: regionCentroid((p) => p[2] < -1.75 && p[1] > 0.75 && Math.abs(p[0]) < 1.3),
  contact: regionCentroid((p) => p[1] < -2.0 && Math.abs(p[0]) < 0.72 && p[2] > 0.25),
}

const flat = new Float32Array(surface.length * 3)
for (let i = 0; i < surface.length; i++) {
  flat[i * 3] = surface[i][0]
  flat[i * 3 + 1] = surface[i][1]
  flat[i * 3 + 2] = surface[i][2]
}

const body = `// Auto-generated by scripts/bake-brain-cloud.mjs — do not edit by hand.
// Brain mesh: "Human brain, Cerebrum & Brainstem" by FrankJohansson (CC BY 4.0)
// https://sketchfab.com/3d-models/human-brain-cerebrum-brainstem-0aa0e33c5c854d1bab7bac9e1c7acaec

export const BRAIN_SCALE = ${SCALE}
export const BRAIN_SURFACE_COUNT = ${surface.length}

const _raw = [${Array.from(flat).map((n) => +n.toFixed(4)).join(',')}]

export const brainSurface = new Float32Array(_raw)

export const brainHotspots = ${JSON.stringify(hotspots, null, 2)} as const
`

writeFileSync(OUT, body)
console.log('Wrote', OUT, `(${surface.length} points, scale ${SCALE})`)
console.log('Hotspots:', hotspots)
